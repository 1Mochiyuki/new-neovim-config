local M = {}

function M.setup()
  local map = function(lhs, fn, desc)
    vim.keymap.set('n', lhs, fn, { desc = desc })
  end

  map('<leader>sh', function()
    Snacks.picker.help()
  end, '[S]earch [H]elp')
  map('<leader>sk', function()
    Snacks.picker.keymaps()
  end, '[S]earch [K]eymaps')
  map('<leader><space>', function()
    Snacks.picker.files()
  end, '[S]earch [F]iles')
  map('<leader>ss', function()
    Snacks.picker.pick()
  end, '[S]earch [S]elect Picker')
  map('<leader>cw', function()
    Snacks.picker.grep_word()
  end, '[S]earch current [W]ord')
  map('<leader>sg', function()
    Snacks.picker.grep()
  end, '[S]earch by [G]rep')
  map('<leader>sA', function()
    require('custom.plugins.ui.ast-grep').search()
  end, '[S]earch by [A]ST')
  map('<leader>sd', function()
    Snacks.picker.diagnostics()
  end, '[S]earch [D]iagnostics')
  map('<leader>sr', function()
    Snacks.picker.resume()
  end, '[S]earch [R]esume')
  map('<leader>s.', function()
    Snacks.picker.recent()
  end, '[S]earch Recent Files ("." for repeat)')
  map('<leader>b', function()
    Snacks.picker.buffers()
  end, '[ ] Find existing buffers')
  map('<leader>/', function()
    Snacks.picker.lines()
  end, '[/] Fuzzily search in current buffer')
  map('<leader>s/', function()
    Snacks.picker.grep_buffers()
  end, '[S]earch [/] in Open Files')
  map('<leader>sn', function()
    Snacks.picker.files { cwd = vim.fn.stdpath 'config' }
  end, '[S]earch [N]eovim files')
end

return M
